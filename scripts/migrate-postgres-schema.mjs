#!/usr/bin/env node
// Idempotent PostgreSQL constraints missed by the original SQLite data importer.
import { openAtlasCoreDatabase, exec, one } from './lib/atlas-postgres.mjs';

const sql=openAtlasCoreDatabase();

const uniques=[
  ['route_patterns','route_patterns_identity_unique',['namespace','template','prefix']],
];

const foreignKeys=[
 ['atlas_catalog_items','atlas_catalog_items_namespace_fk',['namespace'],'atlas_catalog_namespaces',['namespace']],
 ['route_patterns','route_patterns_source_fk',['namespace'],'sources',['namespace']],
 ['examples','examples_pattern_fk',['pattern_id'],'route_patterns',['id']],
 ['pattern_checks','pattern_checks_pattern_fk',['pattern_id'],'route_patterns',['id']],
 ['sitemap_links','sitemap_links_source_fk',['namespace'],'sources',['namespace']],
 ['item_routes','item_routes_source_fk',['namespace'],'sources',['namespace']],
 ['item_routes','item_routes_pattern_fk',['pattern_id'],'route_patterns',['id']],
 ['component_url_checks','component_url_checks_source_fk',['namespace'],'sources',['namespace']],
 ['component_url_checks','component_url_checks_route_fk',['namespace','slug'],'item_routes',['namespace','slug']]
];

const ident=x=>{if(!/^[a-z_][a-z0-9_]*$/i.test(x))throw Error('Invalid identifier');

return '"'+x+'"';};

async function hasConstraint(db,table,name){
 const row=await one(db,"SELECT 1 AS ok FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace ns ON ns.oid=t.relnamespace WHERE ns.nspname='atlas' AND t.relname=$1 AND c.conname=$2",[table,name]);

 return Boolean(row);
}

try{
 await sql.begin(async tx=>{
  for(const [table,name,columns] of uniques){
   if(!await hasConstraint(tx,table,name)){
    await exec(tx,'ALTER TABLE atlas.'+ident(table)+' ADD CONSTRAINT '+ident(name)+' UNIQUE('+columns.map(ident).join(',')+')');
    console.log('ADDED_UNIQUE',name);
   }
  }

  for(const table of ['route_patterns','pattern_checks']){
   const column=await one(tx,"SELECT is_identity FROM information_schema.columns WHERE table_schema='atlas' AND table_name=$1 AND column_name='id'",[table]);

   if(column?.is_identity!=='YES'){
    await exec(tx,'ALTER TABLE atlas.'+ident(table)+' ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
    console.log('ADDED_IDENTITY',table);
   }

   await exec(tx,"SELECT setval(pg_get_serial_sequence('atlas."+table+"','id'),COALESCE((SELECT MAX(id) FROM atlas."+table+"),1),true)");
  }

  const deleteRules={
    atlas_catalog_items_namespace_fk:'CASCADE',
    examples_pattern_fk:'CASCADE',
    pattern_checks_pattern_fk:'CASCADE',
    item_routes_pattern_fk:'SET NULL',
    component_url_checks_route_fk:'CASCADE'
  };

  for(const [table,name,columns,referenced,referencedColumns] of foreignKeys){
    const required=deleteRules[name]??'NO ACTION';
    const ruleCode={'CASCADE':'c','SET NULL':'n','NO ACTION':'a'}[required];
    const existing=await one(tx,"SELECT c.confdeltype FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace ns ON ns.oid=t.relnamespace WHERE ns.nspname='atlas' AND t.relname=$1 AND c.conname=$2",[table,name]);

    if(existing?.confdeltype===ruleCode)continue;

    if(existing)await exec(tx,'ALTER TABLE atlas.'+ident(table)+' DROP CONSTRAINT '+ident(name));
    await exec(tx,'ALTER TABLE atlas.'+ident(table)+' ADD CONSTRAINT '+ident(name)+' FOREIGN KEY('+columns.map(ident).join(',')+') REFERENCES atlas.'+ident(referenced)+'('+referencedColumns.map(ident).join(',')+') ON DELETE '+required);
    console.log('UPDATED_FOREIGN_KEY',name,required);
  }

  await exec(tx,"ALTER TABLE atlas.route_patterns ALTER COLUMN status SET DEFAULT 'unverified'");
  await exec(tx,"ALTER TABLE atlas.item_routes ALTER COLUMN status SET DEFAULT 'unverified'");
  await exec(tx,'ALTER TABLE atlas.component_url_checks ALTER COLUMN attempts SET DEFAULT 0');
  await exec(tx,'CREATE INDEX IF NOT EXISTS atlas_patterns_status_idx ON atlas.route_patterns(namespace,status)');
  await exec(tx,'CREATE INDEX IF NOT EXISTS atlas_items_status_idx ON atlas.item_routes(status)');
  await exec(tx,'CREATE INDEX IF NOT EXISTS atlas_component_checks_status_idx ON atlas.component_url_checks(status,namespace)');
 });
 console.log('POSTGRES_MAINTENANCE_SCHEMA_READY');
}catch(e){console.error('POSTGRES_SCHEMA_MIGRATION_FAILED',e.code||'error',e.message);process.exitCode=1}
finally{await sql.close()}
